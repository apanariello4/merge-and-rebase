KEYWORDS = ["practical", "community", "balance", "future", "simple", "careful", "energy", "season", "history",
            "patience", "creative", "local", "quality", "routine", "journey", "light", "water", "health", "budget",
            "friendship"]
PHRASES = ["Thank you for reading.", "That is all for today.", "Let me know what you think.",
           "Have a wonderful day.", "See you next time."]
LANGS = ["Italian", "French", "Spanish", "German"]
FIRSTS = ["Imagine", "Today", "Many", "Every", "Before"]


def fill(c: str, rng: random.Random) -> str:
    k1, k2 = rng.sample(KEYWORDS, 2)
    return c.format(n=rng.randint(3, 6), w=rng.choice([150, 200, 250, 300]), s=rng.choice([60, 80, 100, 120]),
                    k1=k1, k2=k2, phrase=rng.choice(PHRASES), m=rng.randint(2, 4), h=rng.randint(2, 4),
                    p=rng.randint(2, 4), r=rng.randint(2, 3), f=rng.randint(2, 3), letter=rng.choice("aeiost"),
                    lf=rng.choice([10, 15, 20]), sent=rng.randint(3, 5), lang=rng.choice(LANGS),
                    cap=rng.randint(2, 4), first=rng.choice(FIRSTS))


def main():
    assert len(TASKS) == 180 and len(set(TASKS)) == 180, len(TASKS)
    rng = random.Random(20261120)
    order = []
    while len(order) < 270:
        cyc = list(range(len(CONSTRAINTS)))
        rng.shuffle(cyc)
        order += cyc
    tasks = list(range(180)) + rng.sample(range(180), 90)
    used = {}
    out = []
    for i, t in enumerate(tasks):
        c = order[i]
        while c in used.get(t, set()):  # a task reused never gets the same constraint twice
            c = (c + 1) % len(CONSTRAINTS)
        used.setdefault(t, set()).add(c)
        out.append(f"{TASKS[t]}. {fill(CONSTRAINTS[c], rng)}")
    assert len(set(out)) == 270
    json.dump({"source": __doc__.strip(), "prompts": out}, open(__file__.replace("make_claude_more.py",
              "claude_more_raw.json"), "w"), indent=1)
    print(len(out))


if __name__ == "__main__":
    main()
